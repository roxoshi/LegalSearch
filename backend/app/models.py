class DocType(enum.Enum):
    """Discriminator enum shared by CrossReference source/target columns."""

    act = "act"
    rule = "rule"
    notification = "notification"
    circular = "circular"


class Act(Base):
    """One section of a GST act (CGST, IGST, UTGST, Compensation, Constitution Amendment).

    Each JSON item in .data/acts/ maps to one row.
    primary_id comes from the source system and is the value embedded in
    cross-reference URLs (explore-act/{primary_id}).
    """

    __tablename__ = "acts"

    id = Column(Integer, primary_key=True, autoincrement=True)
    primary_id = Column(Integer, nullable=False)
    content_id = Column(BigInteger, nullable=False, unique=True)  # prefix 1111x
    act_name = Column(Text, nullable=False)       # "CGST Act", "IGST Act", …
    chapter_no = Column(Text, nullable=True)      # "Chapter I"
    chapter_name = Column(Text, nullable=True)    # "Preliminary"
    section_no = Column(Text, nullable=False)     # "Section 1"
    section_name = Column(Text, nullable=True)
    content = Column(Text, nullable=True)         # plain text for FTS / search
    html_content = Column(Text, nullable=True)    # raw HTML for rendering
    source_url = Column(Text, nullable=True)
    # Gemini-generated annotations for semantic search enrichment
    q1 = Column(Text, nullable=True)       # practitioner question 1
    q2 = Column(Text, nullable=True)       # practitioner question 2
    q3 = Column(Text, nullable=True)       # practitioner question 3
    ann_summary = Column(Text, nullable=True)  # one-sentence plain-English summary
    # 384-dim semantic embedding (all-MiniLM-L6-v2); nullable so rows can be
    # inserted before the embedding step runs.
    embedding = Column(Vector(768), nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(DateTime(timezone=True), server_default=func.now(),
                        onupdate=func.now(), nullable=False)

    cross_references_out = relationship(
        "CrossReference",
        primaryjoin="and_(CrossReference.source_type=='act', "
                    "foreign(CrossReference.source_id)==Act.primary_id)",
        viewonly=True,
    )

    __table_args__ = (
        Index("idx_acts_primary_id", "primary_id"),
        Index("idx_acts_act_name", "act_name"),
        Index("idx_acts_chapter", "act_name", "chapter_no"),
        Index(
            "idx_acts_fts",
            text("to_tsvector('english', coalesce(content, ''))"),
            postgresql_using="gin",
        ),
        Index(
            "idx_acts_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )


class ActChunk(Base):
    """A sub-section chunk of an Act section with its vector embedding.

    Each Act row is split at top-level numbered sub-section boundaries
    (e.g. (1), (2), (5)) so that searches hit the precise sub-section
    rather than the entire section blob.
    """

    __tablename__ = "act_chunks"
    __table_args__ = (
        Index(
            "idx_act_chunks_fts",
            text("to_tsvector('english', chunk_content)"),
            postgresql_using="gin",
        ),
        Index(
            "idx_act_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    act_id = Column(Integer, ForeignKey("acts.id", ondelete="CASCADE"), nullable=False)
    # e.g. "Section 17(5)" or "Section 17" for the preamble
    sub_section_label = Column(Text, nullable=False)
    chunk_content = Column(Text, nullable=False)
    # LLM-augmented text: plain-English questions + summary prepended to chunk_content.
    # When present, this is what gets embedded instead of raw chunk_content.
    # Populated by etl/augment_acts.py (one-time Claude Batch API pass).
    embedding_text = Column(Text, nullable=True)
    # 768-dim embedding (all-mpnet-base-v2) — larger model than case law chunks
    embedding = Column(Vector(768), nullable=True)

    act = relationship("Act", backref="chunks")


