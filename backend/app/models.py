class SubscriptionPlan(enum.Enum):
    trial = "trial"
    basic = "basic"
    pro = "pro"


class SubscriptionStatus(enum.Enum):
    active = "active"
    expired = "expired"
    cancelled = "cancelled"


class User(Base):
    """Registered user account. Auth is handled via linked UserIdentity records."""

    __tablename__ = "users"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid4)
    first_name = Column(String(50), nullable=False)
    last_name = Column(String(50), nullable=False)
    year_of_birth = Column(Integer, nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

    # A user can have multiple auth methods (email, phone, Google)
    identities = relationship(
        "UserIdentity", back_populates="user", cascade="all, delete-orphan"
    )
    subscription = relationship(
        "UserSubscription", back_populates="user", uselist=False, cascade="all, delete-orphan"
    )

    __table_args__ = (
        CheckConstraint("year_of_birth > 1900", name="ck_users_year_of_birth"),
    )


class UserIdentity(Base):
    """Links a user to an external auth provider (email OTP, phone OTP, Google OAuth).

    provider_id is the provider-specific unique identifier:
      - email/phone: the address/number itself
      - google: the Google sub claim
    """

    __tablename__ = "user_identities"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid4)
    user_id = Column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    provider = Column(String(20), nullable=False)  # 'email', 'phone', 'google'
    provider_id = Column(String(255), nullable=False)
    is_verified = Column(Boolean, default=False)

    user = relationship("User", back_populates="identities")

    __table_args__ = (
        # Each (provider, provider_id) pair must be globally unique
        UniqueConstraint("provider", "provider_id", name="uq_identity_provider_id"),
    )


class UserSubscription(Base):
    """Tracks a user's subscription plan and free trial window.

    Every new user gets a 7-day trial automatically.
    Trial validity: trial_start ≤ now < trial_end (both UTC).
    """

    __tablename__ = "user_subscriptions"

    id = Column(Integer, primary_key=True, autoincrement=True)
    user_id = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
    )
    plan = Column(
        Enum(SubscriptionPlan), nullable=False, default=SubscriptionPlan.trial
    )
    status = Column(
        Enum(SubscriptionStatus), nullable=False, default=SubscriptionStatus.active
    )
    trial_start = Column(DateTime(timezone=True), nullable=True)
    trial_end = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    user = relationship("User", back_populates="subscription")


class OTPCode(Base):
    """Stores a pending OTP challenge for email/phone login.

    The OTP value itself is hashed; the plaintext is never stored.
    Expired or used codes should be purged periodically.
    """

    __tablename__ = "otp_codes"

    id = Column(Integer, primary_key=True, autoincrement=True)
    # Email address or phone number the OTP was sent to
    identifier = Column(String(255), index=True, nullable=False)
    otp_hash = Column(String(255), nullable=False)
    expires_at = Column(DateTime(timezone=True), nullable=False)
    # Tracks failed verification attempts to support rate-limiting / lockout
    attempts = Column(Integer, default=0)


class Document(Base):
    """A single GST judgment. Metadata is sourced from the parquet files produced
    by the sharding pipeline; content is the HTML generated by the ETL transform step.

    case_id is the canonical dedup key — upserting a document deletes the old record
    and all its chunks before inserting the new one.
    """

    __tablename__ = "documents"

    id = Column(Integer, primary_key=True, index=True)
    title = Column(Text, nullable=False)
    petitioner = Column(Text, nullable=False)
    respondent = Column(Text, nullable=False)
    judge = Column(Text, nullable=False)
    citation = Column(Text, nullable=False)
    decision_date = Column(Text, nullable=False)
    disposal_nature = Column(Text, nullable=True)
    court = Column(Text, nullable=False)
    # Stable identifier from source data (e.g. CNR number); unique across all docs
    case_id = Column(Text, nullable=False, unique=True)
    # Raw text used for full-text or fallback search
    content = Column(Text, nullable=False)
    # HTML rendered for the document detail page (may be None for legacy records)
    display_content = Column(Text, nullable=True)

    # ML-extracted fields from filter step
    is_gst_core = Column(Boolean, nullable=True, default=None)
    extracted_provisions: Column = Column(ARRAY(Text), nullable=True)
    extracted_statutes: Column = Column(ARRAY(Text), nullable=True)

    # (Section, Act) pairs extracted from analysis JSONs — "Section 16|CGST Act"
    # Populated by etl/extract_act_sections.py
    act_sections: Column = Column(ARRAY(Text), nullable=True)
    # Convenience: just the provision strings without act suffix (legacy extract_provisions.py)
    primary_provisions: Column = Column(ARRAY(Text), nullable=True)

    # Timestamps for sync support
    created_at = Column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    chunks = relationship("DocumentChunk", back_populates="document")


class DocumentChunk(Base):
    """A text chunk of a Document with its vector embedding.

    Documents are split into chunks of ~4000 chars (600 char overlap) by the ETL
    transform step. Each chunk stores a 384-dim embedding produced by
    all-MiniLM-L6-v2, used for cosine-distance similarity search via pgvector.
    """

    __tablename__ = "document_chunks"
    __table_args__ = (
        Index(
            "idx_chunks_fts",
            text("to_tsvector('english', chunk_content)"),
            postgresql_using="gin",
        ),
    )

    id = Column(Integer, primary_key=True, index=True)
    document_id = Column(Integer, ForeignKey("documents.id"), nullable=False)
    chunk_content = Column(Text, nullable=False)
    # 384-dimensional embedding vector (all-MiniLM-L6-v2)
    embedding = Column(Vector(768))
    document = relationship("Document", back_populates="chunks")


