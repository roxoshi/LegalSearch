class LibraryChunk(Base):
    """A text chunk of a Notification or Circular with its vector embedding.

    Populated by etl/embed_library_docs.py. Used for hybrid FTS + semantic
    search over notifications and circulars separately.
    """

    __tablename__ = "library_chunks"

    id = Column(Integer, primary_key=True, autoincrement=True)
    doc_type = Column(Text, nullable=False)       # 'notification' or 'circular'
    primary_id = Column(Integer, nullable=False)
    chunk_index = Column(Integer, nullable=False)
    content = Column(Text, nullable=False)
    embedding_text = Column(Text, nullable=True)  # LLM-generated prefix (questions + summary)
    embedding = Column(Vector(768), nullable=True)

    __table_args__ = (
        UniqueConstraint("doc_type", "primary_id", "chunk_index", name="uq_library_chunk"),
        Index("idx_library_chunks_lookup", "doc_type", "primary_id"),
        Index(
            "idx_library_chunks_fts",
            text("to_tsvector('english', content)"),
            postgresql_using="gin",
        ),
        Index(
            "idx_library_chunks_embedding",
            "embedding",
            postgresql_using="ivfflat",
            postgresql_ops={"embedding": "vector_cosine_ops"},
            postgresql_with={"lists": 100},
        ),
    )


class CrossReference(Base):
    """A hyperlink parsed from html_content of an Act or Rule pointing to another document.

    source_type / source_id  — the Act or Rule section the link appears in.
    target_type / target_id  — the document the link points to (primary_id of that table).

    Links follow the pattern: explore-{target_type}/{target_id}
    Populated entirely by the ingestion pipeline; never written by the API.
    """

    __tablename__ = "cross_references"

    id = Column(Integer, primary_key=True, autoincrement=True)
    source_type = Column(Enum(DocType), nullable=False)
    source_id = Column(Integer, nullable=False)    # primary_id of the source Act/Rule
    target_type = Column(Enum(DocType), nullable=False)
    target_id = Column(Integer, nullable=False)    # primary_id of the target document
    anchor_text = Column(Text, nullable=True)      # visible link text
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (
        UniqueConstraint(
            "source_type", "source_id", "target_type", "target_id",
            name="uq_cross_reference",
        ),
        Index("idx_xref_source", "source_type", "source_id"),
        Index("idx_xref_target", "target_type", "target_id"),
    )


class XrefRelationship(enum.Enum):
    """Validity relationship between two library documents (notifications/circulars)."""
    WITHDRAWS  = "WITHDRAWS"   # from_doc completely withdraws / rescinds to_doc
    SUPERSEDES = "SUPERSEDES"  # from_doc replaces to_doc (to_doc is no longer operative)
    AMENDS     = "AMENDS"      # from_doc partially modifies to_doc (to_doc still valid)


class LibraryXref(Base):
    """Validity relationships between notifications and circulars.

    from_doc (the newer document) has relationship WITHDRAWS/SUPERSEDES/AMENDS to_doc.
    When relationship is WITHDRAWS or SUPERSEDES, to_doc.is_active should be False.
    Populated by etl/build_xrefs.py; never written by the API.
    """

    __tablename__ = "library_xrefs"

    id             = Column(Integer, primary_key=True, autoincrement=True)
    from_doc_type  = Column(Enum(DocType), nullable=False)
    from_primary_id = Column(Integer, nullable=False)
    to_doc_type    = Column(Enum(DocType), nullable=False)
    to_primary_id  = Column(Integer, nullable=False)
    relationship   = Column(Enum(XrefRelationship), nullable=False)
    ab_initio      = Column(Boolean, nullable=False, default=False)  # withdrawn as if never issued
    created_at     = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (
        UniqueConstraint(
            "from_doc_type", "from_primary_id", "to_doc_type", "to_primary_id",
            name="uq_library_xref",
        ),
        Index("idx_lxref_from", "from_doc_type", "from_primary_id"),
        Index("idx_lxref_to",   "to_doc_type",   "to_primary_id"),
    )
